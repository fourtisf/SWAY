#!/usr/bin/env node
// Exports contract ABIs from contracts/out into packages/shared/src/abi as typed `as const` arrays.
// Run after `forge build` whenever a contract's external interface changes: `node scripts/export-abi.mjs`.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = resolve(root, 'packages/shared/src/abi');
const names = process.argv.slice(2).length
  ? process.argv.slice(2)
  : ['SwayKeys', 'FanEscrow', 'SwayStaking', 'GenesisPass', 'SwayLaunchpad', 'SwayCreatorToken', 'SwayDrops'];
mkdirSync(outDir, { recursive: true });
const exported = [];
for (const name of names) {
  const file = resolve(root, `contracts/out/${name}.sol/${name}.json`);
  if (!existsSync(file)) {
    console.warn(`skip ${name}: ${file} not found (run forge build)`);
    continue;
  }
  const { abi } = JSON.parse(readFileSync(file, 'utf8'));
  const id = name[0].toLowerCase() + name.slice(1) + 'Abi';
  writeFileSync(
    resolve(outDir, `${name}.ts`),
    `// Generated by scripts/export-abi.mjs from contracts/out/${name}.sol. Do not edit.\nexport const ${id} = ${JSON.stringify(abi, null, 2)} as const;\n`,
  );
  exported.push([name, id]);
}
writeFileSync(
  resolve(outDir, 'index.ts'),
  `// Generated by scripts/export-abi.mjs. Do not edit.\n` + exported.map(([n, id]) => `export { ${id} } from './${n}';`).join('\n') + '\n',
);
console.log(`exported ${exported.map(([n]) => n).join(', ')}`);
